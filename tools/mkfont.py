FIRST, LAST = 32, 95


def glyph_bytes(rows: list[str]) -> list[int]:
    out = []
    for r in rows + ["......."]:
        if len(r) != 7:
            raise ValueError(f"bad row {r!r}")
        b = 0
        for i, ch in enumerate(r):
            if ch == "#":
                b |= 0x80 >> i
        out.append(b)
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: mkfont.py <out.c>", file=sys.stderr)
        return 1
    lines = ['#include "font.h"', "", f"const uint8_t font_1bpp[FONT_COUNT * 8] = {{"]
    for code in range(FIRST, LAST + 1):
        rows = GLYPHS.get(chr(code))
        data = glyph_bytes(rows) if rows else [0] * 8
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data) + ",")
    lines.append("};")
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
